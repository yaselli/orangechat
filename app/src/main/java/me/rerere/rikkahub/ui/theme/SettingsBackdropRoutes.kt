package me.rerere.rikkahub.ui.theme

import me.rerere.rikkahub.Screen

/** Explicit route scope, independent of class names and release obfuscation. */
internal val Screen.usesSettingsBackdrop: Boolean
    get() =
        when (this) {
            Screen.Assistant,
            is Screen.AssistantDetail,
            is Screen.AssistantBasic,
            is Screen.AssistantPrompt,
            is Screen.AssistantMemory,
            is Screen.AssistantRequest,
            is Screen.AssistantMcp,
            is Screen.AssistantLocalTool,
            is Screen.AssistantInjections,
            Screen.Setting,
            Screen.Backup,
            Screen.MediaCreationSessions,
            is Screen.MediaCreation,
            Screen.SettingMedia,
            Screen.SettingDisplay,
            Screen.SettingTheme,
            Screen.SettingDisplayTheme,
            Screen.SettingDisplayColor,
            Screen.SettingDisplayTransparency,
            Screen.SettingDisplayIllustration,
            Screen.SettingDisplayMessage,
            Screen.SettingDisplayCodeInteraction,
            Screen.SettingDisplayGeneral,
            Screen.SettingDisplayNotification,
            Screen.SettingProvider,
            is Screen.SettingProviderDetail,
            Screen.SettingModels,
            Screen.SettingAbout,
            Screen.UpdateDownload,
            Screen.SettingSearch,
            is Screen.SettingSearchDetail,
            Screen.SettingSpeech,
            Screen.SettingMcp,
            Screen.SettingDonate,
            Screen.SettingFiles,
            Screen.SettingWeb,
            Screen.Developer,
            Screen.Debug,
            Screen.Log,
            Screen.SecurityAudit,
            Screen.Extensions,
            Screen.QuickMessages,
            Screen.Prompts,
            Screen.Skills,
            is Screen.SkillDetail,
            Screen.Workspaces,
            is Screen.WorkspaceDetail,
            is Screen.WorkspaceTerminal,
            Screen.SettingSystemTools,
            Screen.SettingSecurity,
            Screen.SettingProactiveMessage,
            Screen.SettingExtraInjection,
            Screen.SettingPlugins,
            Screen.Workflows,
            is Screen.WorkflowDetail,
            is Screen.PluginDetail,
            is Screen.PluginFolder,
            is Screen.PluginWebView,
            is Screen.PluginDeclarativeUI,
            Screen.MemoryBank,
            Screen.MiniAppManager,
            is Screen.MiniAppEdit,
            is Screen.Legal -> true
            else -> false
        }
