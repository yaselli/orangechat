#!/usr/bin/env python3
"""Exercise production v41->v42 SQL and compare with Room's actual exported schema."""
import argparse
import json
from pathlib import Path
import re
import sqlite3

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--require-schema", action="store_true")
args = parser.parse_args()
assert re.search(r"version\s*=\s*(?:42|43)", (root / "app/src/main/java/me/rerere/rikkahub/data/db/AppDatabase.kt").read_text())
assert "Migration_41_42," in (root / "app/src/main/java/me/rerere/rikkahub/di/DataSourceModule.kt").read_text()
schemas = root / "app/schemas/me.rerere.rikkahub.data.db.AppDatabase"
before = json.loads((schemas / "41.json").read_text())["database"]
sql_file = root / "app/src/main/java/me/rerere/rikkahub/data/db/migrations/Migration_41_42.kt"
sql = re.findall(r'db\.execSQL\("([^"\n]+)"\)', sql_file.read_text())
assert len(sql) == 2, "Unexpected migration shape"


def database(schema):
    db = sqlite3.connect(":memory:")
    for entity in schema["entities"]:
        db.execute(entity["createSql"].replace("${TABLE_NAME}", entity["tableName"]))
        for index in entity.get("indices", []):
            db.execute(index["createSql"].replace("${TABLE_NAME}", entity["tableName"]))
    return db


db = database(before)
db.execute("INSERT INTO workspaces(id,name,root,shell_status,created_at,updated_at,tool_approvals) "
           "VALUES('old','旧工作区','old-root','READY',1,2,'{\"workspace_shell\":true}')")
db.execute("INSERT INTO MemoryEntity(id,assistant_id,content) VALUES(9,'owner','旧记忆🌶')")
tables = [entity["tableName"] for entity in before["entities"]]
old_rows = {table: list(db.execute(f'SELECT * FROM "{table}"')) for table in tables}
old_columns = {table: [row[1] for row in db.execute(f'PRAGMA table_info("{table}")')] for table in tables}
db.commit()
db.execute("BEGIN")
for command in sql:
    db.execute(command)
db.rollback()
assert "type" not in [row[1] for row in db.execute("PRAGMA table_info(workspaces)")]
for command in sql:
    db.execute(command)
for table in tables:
    columns = ",".join('"' + column + '"' for column in old_columns[table])
    assert list(db.execute(f'SELECT {columns} FROM "{table}"')) == old_rows[table], table
assert db.execute("SELECT type,ssh_config FROM workspaces WHERE id='old'").fetchone() == ("LOCAL", None)
db.execute("INSERT INTO workspaces(id,name,root,shell_status,created_at,updated_at,type,ssh_config) "
           "VALUES('remote','SSH','remote-root','READY',3,4,'SSH','{\"encryptedPassword\":\"enc:v1:test\"}')")
db.execute("DELETE FROM workspaces WHERE id='remote'")
assert db.execute("SELECT COUNT(*) FROM workspaces").fetchone()[0] == 1
print("PASS: production v41->v42 rollback, old tables/rows/approvals, LOCAL defaults and SSH row deletion")

exported = schemas / "42.json"
if exported.exists():
    expected = database(json.loads(exported.read_text())["database"])
    for table in tables:
        assert list(db.execute(f'PRAGMA table_info("{table}")')) == list(
            expected.execute(f'PRAGMA table_info("{table}")')), table
        assert list(db.execute(f'PRAGMA index_list("{table}")')) == list(
            expected.execute(f'PRAGMA index_list("{table}")')), table
        assert list(db.execute(f'PRAGMA foreign_key_list("{table}")')) == list(
            expected.execute(f'PRAGMA foreign_key_list("{table}")')), table
    print("PASS: migration matches compiler-exported Room v42 schema")
elif args.require_schema:
    raise SystemExit("Missing real compiler-exported v42 schema")
else:
    print("PENDING: Room v42 export is generated by CI; no placeholder schema created")
