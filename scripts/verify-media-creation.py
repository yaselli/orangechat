#!/usr/bin/env python3
"""Run production media migration SQL against the real v42 Room export."""
import json
import re
import sqlite3
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schemas = root / 'app/schemas/me.rerere.rikkahub.data.db.AppDatabase'
source = root / 'app/src/main/java/me/rerere/rikkahub'
sql = re.findall(r'db\.execSQL\("([^"\n]+)"\)',
    (source / 'data/db/migrations/Migration_42_43.kt').read_text())
assert len(sql) == 6
assert 'Migration_42_43,' in (source / 'di/DataSourceModule.kt').read_text()
assert re.search(r'version\s*=\s*43', (source / 'data/db/AppDatabase.kt').read_text())


def database(schema):
    db = sqlite3.connect(':memory:')
    db.execute('PRAGMA foreign_keys=ON')
    for entity in schema['entities']:
        # FTS is independently covered on Android with the native extension.
        if 'ftsOptions' in entity:
            continue
        table = entity['tableName']
        db.execute(entity['createSql'].replace('${TABLE_NAME}', table))
        for index in entity.get('indices', []):
            db.execute(index['createSql'].replace('${TABLE_NAME}', table))
    return db


before = json.loads((schemas / '42.json').read_text())['database']
db = database(before)
db.execute("INSERT INTO MemoryEntity(id,assistant_id,content) VALUES(7,'owner','原记忆')")
db.execute("INSERT INTO GenMediaEntity(path,model_id,prompt,create_at,type) VALUES('old.png','m','旧生图',1,'image_generation')")
db.execute("INSERT INTO workspaces(id,name,root,shell_status,created_at,updated_at,type,ssh_config) "
           "VALUES('ssh','远程','remote','READY',1,2,'SSH','encrypted')")
old_tables = [e['tableName'] for e in before['entities'] if 'ftsOptions' not in e]
old_rows = {t: db.execute(f'SELECT * FROM "{t}"').fetchall() for t in old_tables}
db.commit()
db.execute('BEGIN')
for command in sql:
    db.execute(command)
db.rollback()
assert not db.execute("SELECT name FROM sqlite_master WHERE name LIKE 'media_creation_%'").fetchall()
for command in sql:
    db.execute(command)
for table, rows in old_rows.items():
    assert db.execute(f'SELECT * FROM "{table}"').fetchall() == rows, table
# An actual versioned task, followed by cascade deletion and orphan rejection.
db.execute("INSERT INTO media_creation_session VALUES('s','test','{}',1,2)")
db.execute("INSERT INTO media_creation_node VALUES('n','s','r',1)")
db.execute("INSERT INTO media_creation_record VALUES('r','s','n','p','Provider','model','VIDEO','prompt','{}','[]','RUNNING','task-id',NULL,'[]',1,2)")
assert db.execute("SELECT task_id FROM media_creation_record WHERE status='RUNNING'").fetchone() == ('task-id',)
db.execute("DELETE FROM media_creation_session WHERE id='s'")
assert not db.execute('SELECT * FROM media_creation_node').fetchall()
assert not db.execute('SELECT * FROM media_creation_record').fetchall()
try:
    db.execute("INSERT INTO media_creation_node VALUES('orphan','absent','r',1)")
    raise AssertionError('Orphan accepted')
except sqlite3.IntegrityError:
    pass
export = schemas / '43.json'
if export.exists():
    expected = database(json.loads(export.read_text())['database'])
    for table in [e['tableName'] for e in json.loads(export.read_text())['database']['entities'] if 'ftsOptions' not in e]:
        for pragma in ('table_info', 'index_list', 'foreign_key_list'):
            assert db.execute(f'PRAGMA {pragma}("{table}")').fetchall() == expected.execute(
                f'PRAGMA {pragma}("{table}")').fetchall(), (table, pragma)
    print('PASS: production migration matches the compiler-exported v43 schema')
else:
    print('PENDING: real v43 schema will be generated by CI; no placeholder added')
print('PASS: v42->43 rollback, legacy rows, persistent task IDs, cascade deletion and foreign keys')
